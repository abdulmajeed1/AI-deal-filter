CLIENT = httpx.Client(timeout=25)

def fetch_path(coin, source, entry_dt, days=45):
    """Hourly lows/closes AFTER entry. Returns list of (low, close) oldest-first."""
    start_ms = int(entry_dt.replace(tzinfo=timezone.utc).timestamp()*1000)
    n = days*24
    if source == "binance":
        r = CLIENT.get("https://data-api.binance.vision/api/v3/klines",
            params={"symbol":coin+"USDT","interval":"1h","startTime":start_ms,"limit":min(n,1000)})
        r.raise_for_status()
        return [(float(c[3]), float(c[4])) for c in r.json()]
    else:  # kucoin
        end_s = start_ms//1000 + n*3600
        r = CLIENT.get("https://api.kucoin.com/api/v1/market/candles",
            params={"type":"1hour","symbol":f"{coin}-USDT","startAt":start_ms//1000,"endAt":end_s})
        r.raise_for_status()
        rows = r.json().get("data") or []
        rows.reverse()  # kucoin newest-first
        return [(float(c[4]), float(c[2])) for c in rows]  # (low, close)

def build_ladder(n_so, step, scoef, vcoef, bvol, sovol, total_fund=None):
    """Returns list of (price_drop_frac, volume_at_this_order). If total_fund given, scale SO vols to match."""
    # raw volumes
    vols = [sovol*(vcoef**i) for i in range(n_so)]
    if total_fund is not None:
        raw_total = bvol + sum(vols)
        scale = (total_fund - bvol)/sum(vols)
        vols = [v*scale for v in vols]
    drops, d = [], 0.0
    for i in range(n_so):
        d += step*(scoef**i)
        drops.append(d/100.0)
    return list(zip(drops, vols))

def simulate(deal, path, n_so, total_fund):
    """Replay a deal under a given ladder. Returns (outcome, pl_pct_of_fund)."""
    bp, bvol, sovol = deal['bp'], deal['bv'], deal['sv']
    ladder = build_ladder(n_so, deal['step'], deal['scoef'], deal['vcoef'], bvol, sovol, total_fund)
    tp = deal['tp']/100.0

    # base order fills at entry
    coins = bvol/bp
    spent = bvol
    next_so = 0

    for low, close in path:
        # fill any safety orders whose trigger price >= current low
        while next_so < len(ladder):
            drop, vol = ladder[next_so]
            trigger = bp*(1-drop)
            if low <= trigger:
                coins += vol/trigger
                spent += vol
                next_so += 1
            else:
                break
        avg = spent/coins
        # take-profit check on close
        if close >= avg*(1+tp):
            return "recovered", (spent*tp)/total_fund*100  # profit ~ tp% of deployed
    # never recovered: mark-to-last-close
    last_close = path[-1][1]
    avg = spent/coins
    unreal = (last_close-avg)*coins
    return "stranded", unreal/total_fund*100

