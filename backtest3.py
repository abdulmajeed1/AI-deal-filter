# ---------------- data adapters: all return oldest-first [{open, close, quote_vol}] ----------------

def src_binance(sym, end_ms, n):
    r = CLIENT.get("https://data-api.binance.vision/api/v3/klines",
                   params={"symbol": sym + "USDT", "interval": "1h", "endTime": end_ms, "limit": n})
    r.raise_for_status()
    data = r.json()
    return [{"open": float(c[1]), "close": float(c[4]), "quote_vol": float(c[7])} for c in data]


def src_bybit(sym, end_ms, n):
    r = CLIENT.get("https://api.bybit.com/v5/market/kline",
                   params={"category": "spot", "symbol": sym + "USDT", "interval": "60",
                           "end": end_ms, "limit": n})
    r.raise_for_status()
    rows = r.json()["result"]["list"]  # newest first
    rows.reverse()
    return [{"open": float(c[1]), "close": float(c[4]), "quote_vol": float(c[6])} for c in rows]


def src_kucoin(sym, end_ms, n):
    end_s = end_ms // 1000
    start_s = end_s - n * 3600
    r = CLIENT.get("https://api.kucoin.com/api/v1/market/candles",
                   params={"type": "1hour", "symbol": f"{sym}-USDT",
                           "startAt": start_s, "endAt": end_s})
    r.raise_for_status()
    rows = r.json().get("data") or []  # newest first: [t, open, close, high, low, vol, turnover]
    rows.reverse()
    return [{"open": float(c[1]), "close": float(c[2]), "quote_vol": float(c[6])} for c in rows]


def src_gate(sym, end_ms, n):
    end_s = end_ms // 1000
    start_s = end_s - n * 3600
    r = CLIENT.get("https://api.gateio.ws/api/v4/spot/candlesticks",
                   params={"currency_pair": f"{sym}_USDT", "interval": "1h",
                           "from": start_s, "to": end_s})
    r.raise_for_status()
    rows = r.json()  # oldest first: [t, quote_vol, close, high, low, open, base_vol, ...]
    return [{"open": float(c[5]), "close": float(c[2]), "quote_vol": float(c[1])} for c in rows]


SOURCES = [("binance", src_binance), ("bybit", src_bybit), ("kucoin", src_kucoin), ("gate", src_gate)]


def fetch_candles(sym, entry_dt, hours=192):
    end_ms = int(entry_dt.replace(tzinfo=timezone.utc).timestamp() * 1000)
    tried = SOURCES
    if sym in SOURCE_FOR:  # reuse the source that worked for this symbol
        tried = [s for s in SOURCES if s[0] == SOURCE_FOR[sym]]
    last_err = None
    for name, fn in tried:
        for attempt in range(3):
            try:
                candles = fn(sym, end_ms, hours)
                if len(candles) >= 48:
                    SOURCE_FOR[sym] = name
                    return candles
                last_err = f"{name}: only {len(candles)} candles"
                break
            except Exception as e:
                last_err = f"{name}: {str(e)[:40]}"
                if "429" in str(e):
                    time.sleep(2 * (attempt + 1))
                    continue
                break
    raise RuntimeError(last_err or "no data")


# ---------------- rulesets ----------------

def change_24h(candles):
    last24 = candles[-24:]
    return (last24[-1]["close"] - last24[0]["open"]) / last24[0]["open"] * 100


def ruleset_a(candles):
    ch = change_24h(candles)
    if ch <= -8.0:
        return "skip"
    streak = candles[-4:]
    drop = (streak[-1]["close"] - streak[0]["open"]) / streak[0]["open"] * 100
    if all(c["close"] < c["open"] for c in streak) and drop <= -2.5:
        return "skip"
    last24, baseline = candles[-24:], candles[:-24]
    vol = sum(c["quote_vol"] for c in last24)
    base_avg = sum(c["quote_vol"] for c in baseline) / len(baseline) * 24
    if base_avg > 0 and vol < 0.5 * base_avg:
        return "skip"
    return "enter"


def ruleset_b(candles):
    return "skip" if change_24h(candles) <= -2.0 else "enter"


def ruleset_c(candles):
    return "skip" if change_24h(candles) <= -8.0 else "enter"


# ---------------- run ----------------

def summarize(key, deals):
    lines = []
    for verdict, label in (("enter", "ALLOWED"), ("skip", "BLOCKED")):
        g = [d for d in deals if d[key] == verdict]
        if not g:
            lines.append(f"  {label}: none")
            continue
        total = sum(d["profit"] for d in g)
        stuck = sum(1 for d in g if d["status"] == "STUCK")
        deep = sum(1 for d in g if d["so"] >= 5)
        lines.append(f"  {label}: {len(g):>3} deals | total P/L {total:+9.2f}$ | stuck: {stuck} | deep-SO (>=5): {deep}")
    return "\n".join(lines)


def main():
    results = []
    errors = 0
    t0 = time.time()
    print(f"Checking {len(DEALS)} deals (multi-exchange, ~5-10 min)...\n")

    for i, (sym, entry, status, profit, dur, so) in enumerate(DEALS, 1):
        entry_dt = datetime.strptime(entry, "%Y-%m-%d %H:%M:%S")
        rec = {"sym": sym, "entry": entry, "status": status, "profit": profit, "so": so}
        try:
            candles = fetch_candles(sym, entry_dt)
            rec["a"], rec["b"], rec["c"] = ruleset_a(candles), ruleset_b(candles), ruleset_c(candles)
            rec["ch24"] = change_24h(candles)
        except Exception as e:
            rec["a"] = rec["b"] = rec["c"] = "error"
            rec["err"] = str(e)
            errors += 1
        results.append(rec)

        # print painful deals and a progress line every 50
        painful = status == "STUCK" or so >= 5
        if painful and rec["a"] != "error":
            tag = "STUCK" if status == "STUCK" else f"SO:{so}"
            print(f"  painful deal {sym} {entry} ({tag}, {profit:+.2f}$, 24h {rec['ch24']:+.1f}%) -> "
                  f"A:{rec['a'].upper()} B:{rec['b'].upper()} C:{rec['c'].upper()}")
        if i % 50 == 0:
            print(f"  ... {i}/{len(DEALS)} done ({time.time()-t0:.0f}s, sources: {SOURCE_FOR})")
        time.sleep(0.15)

    ok = [r for r in results if r["a"] != "error"]
    print("\n" + "=" * 95)
    print(f"RESULTS on {len(ok)} deals ({errors} errors, data sources used: {SOURCE_FOR})")
    print("=" * 95)
    print("\nRULESET A — original defaults (dump/red-streak/volume)")
    print(summarize("a", ok))
    print("\nRULESET B — momentum: block 24h < -2%")
    print(summarize("b", ok))
    print("\nRULESET C — crash brake only: block 24h < -8%")
    print(summarize("c", ok))
    print("\nBot total on checked deals: "
          f"{sum(d['profit'] for d in ok):+.2f}$ across {len(ok)} deals")
    if errors:
        errs = [r for r in results if r["a"] == "error"]
        print(f"\nFirst few errors: {[e['sym'] + ' ' + e.get('err','')[:50] for e in errs[:3]]}")


if __name__ == "__main__":
    main()
